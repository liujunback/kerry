-- ==================== 盘点模块主数据 ====================

CREATE TABLE `inventory_count_order` (
  `id` CHAR(36) NOT NULL COMMENT '主键ID',
  `tenant_id` CHAR(36) NOT NULL COMMENT '租户ID',
  `order_number` VARCHAR(32) NOT NULL COMMENT '盘点单号',
  `order_name` VARCHAR(128) NOT NULL COMMENT '盘点单名称',
  `order_type` VARCHAR(32) NOT NULL COMMENT '盘点类型：FULL/LOCATION/SKU/CYCLE',
  `count_mode` VARCHAR(32) NOT NULL COMMENT '盘点方式：BLIND/OPEN',
  `status` VARCHAR(32) NOT NULL DEFAULT 'DRAFT' COMMENT '状态：DRAFT/PENDING_SCOPE/READY/IN_PROGRESS/PENDING_ADJUST/COMPLETED/CANCELLED',
  `warehouse_id` CHAR(36) NOT NULL COMMENT '仓库ID',
  `warehouse_name` VARCHAR(64) NOT NULL COMMENT '仓库名称',
  `planned_at` DATETIME(3) NOT NULL COMMENT '计划执行时间',
  `remark` VARCHAR(500) NULL COMMENT '备注',
  `owner_scope_mode` VARCHAR(32) NOT NULL DEFAULT 'ALL' COMMENT '货主范围模式：ALL/PARTIAL',
  `owner_scope_summary` VARCHAR(255) NOT NULL DEFAULT '全部货主' COMMENT '货主范围摘要',
  `owner_scope_config_json` JSON NOT NULL COMMENT '货主范围配置',
  `scope_config_json` JSON NOT NULL COMMENT '盘点范围配置',
  `execution_config_json` JSON NOT NULL COMMENT '执行规则配置',
  `total_batch_count` INT NOT NULL DEFAULT 0 COMMENT '总批次数',
  `completed_batch_count` INT NOT NULL DEFAULT 0 COMMENT '已完成批次数',
  `total_detail_count` INT NOT NULL DEFAULT 0 COMMENT '总明细数',
  `diff_detail_count` INT NOT NULL DEFAULT 0 COMMENT '差异明细数',
  `pending_recount_count` INT NOT NULL DEFAULT 0 COMMENT '待复盘数',
  `pending_adjust_count` INT NOT NULL DEFAULT 0 COMMENT '待调整数',
  `created_by` CHAR(36) NULL COMMENT '创建人',
  `updated_by` CHAR(36) NULL COMMENT '更新人',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
  UNIQUE INDEX `inventory_count_order_tenant_id_order_number_key`(`tenant_id`, `order_number`),
  INDEX `inventory_count_order_tenant_id_warehouse_id_status_idx`(`tenant_id`, `warehouse_id`, `status`),
  INDEX `inventory_count_order_planned_at_idx`(`planned_at`),
  INDEX `inventory_count_order_order_type_idx`(`order_type`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci COMMENT='盘点单主表';

